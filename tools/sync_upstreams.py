#!/usr/bin/env python3
"""Refresh pinned source snapshots and regenerate namespace-only import adapters.

Default: regenerate from local snapshots, offline. --check verifies hashes and
adapters without writing. --update fetches main into temporary Git repositories;
it never imports/executes upstream code. Every proposed update still needs review.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "vendor/upstream-lock.json"
# Namespace imports and bounded filesystem cleanup only; scientific expressions stay intact.
REPLACEMENTS = {
    ("SoFT", "soft/soft.py"): [
        ("import os", "import os\nimport shutil"),
        ('            os.system(f"rm -rf {datapath}temp*")',
         '            for index in range(10):\n'
         '                temporary = os.path.join(datapath, f"temp{index}")\n'
         '                if os.path.isdir(temporary) and not os.path.islink(temporary):\n'
         '                    shutil.rmtree(temporary)'),
    ],
    ("SoFT", "soft/extras.py"): [("import soft.soft as st", "from . import soft as st")],
    ("SoFTg", "granule_detection_lib.py"): [("import soft.soft as st", "from ..soft import soft as st")],
    ("SoFTg", "label_tool.py"): [
        ("from utils import slice_into_tiles", "from .utils import slice_into_tiles"),
        ("from granule_detection_lib import segment_solar_granules", "from .granule_detection_lib import segment_solar_granules"),
    ],
    ("SoFTg", "predict.py"): [("from model import UNetPlusPlus", "from .model import UNetPlusPlus"), ("import utils", "from . import utils")],
    ("SoFTg", "train.py"): [
        ("import dataset", "from . import dataset"), ("import losses", "from . import losses"),
        ("import model as model_module", "from . import model as model_module"), ("import utils", "from . import utils"),
    ],
}


def digest(content):
    return hashlib.sha256(content).hexdigest()


def git(*args, cwd):
    return subprocess.check_output(["git", *args], cwd=cwd)


def generated(snapshots):
    result = {}
    for name, files in snapshots.items():
        package = "soft" if name == "SoFT" else "softg"
        prefix = ROOT / "src/WaLSAlib/_vendor" / package
        # SoFT's original initializer imports a global `soft`; use a minimal,
        # namespaced initializer instead. The original remains in vendor/.
        result[prefix / "__init__.py"] = b'"""Private upstream package; generated by tools/sync_upstreams.py."""\n'
        for path, content in files.items():
            if not path.endswith(".py") or path in {"setup.py", "soft/__init__.py"}:
                continue
            target = prefix / (path.removeprefix("soft/") if name == "SoFT" else path)
            source = content.decode("utf-8")
            for old, new in REPLACEMENTS.get((name, path), []):
                if source.splitlines().count(old) != 1:
                    raise ValueError(f"{name}/{path}: import adapter needs review: {old!r}")
                source = source.replace(old + "\n", new + "\n", 1)
            result[target] = source.encode("utf-8")
    return result


def run(check=False, update=False):
    lock = json.loads(LOCK.read_text())
    snapshots = {}
    for name, config in lock["components"].items():
        files = config["files"]
        if update:
            with tempfile.TemporaryDirectory(prefix="walsalib-upstream-") as tmp:
                git("init", "--quiet", cwd=tmp)
                git("fetch", "--quiet", "--depth=1", config["repository"], config["ref"], cwd=tmp)
                commit = git("rev-parse", "FETCH_HEAD", cwd=tmp).decode().strip()
                snapshots[name] = {path: git("show", f"{commit}:{path}", cwd=tmp) for path in files}
                # Any licensing change needs an explicit maintainer decision.
                if snapshots[name]["LICENSE"] != (ROOT / "vendor" / name / "LICENSE").read_bytes():
                    raise ValueError(f"{name}: upstream license changed; review before updating")
                config["commit"] = commit
        else:
            snapshots[name] = {path: (ROOT / "vendor" / name / path).read_bytes() for path in files}
        hashes = {path: digest(data) for path, data in snapshots[name].items()}
        if not update and hashes != config["sha256"]:
            raise ValueError(f"{name}: snapshot hashes differ from upstream-lock.json")
        config["sha256"] = hashes
        print(f"{name}: {config['commit']}")
    outputs = generated(snapshots)  # validate every adapter before writing anything
    if check:
        expected_paths = set(outputs)
        actual_paths = set((ROOT / "src/WaLSAlib/_vendor").glob("*/*.py"))
        if actual_paths != expected_paths:
            raise ValueError("Generated vendor file list differs; regenerate adapters")
        for path, content in outputs.items():
            if not path.exists() or path.read_bytes() != content:
                raise ValueError(f"Stale adapter: {path.relative_to(ROOT)}")
        return
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    if update:
        for name, files in snapshots.items():
            for path, content in files.items():
                (ROOT / "vendor" / name / path).write_bytes(content)
        LOCK.write_text(json.dumps(lock, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--update", action="store_true")
    args = parser.parse_args()
    run(check=args.check, update=args.update)
